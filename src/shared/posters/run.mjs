// Dev-time only: bundles gen.ts with esbuild, runs it, writes data.ts. `node src/shared/posters/run.mjs`
import { build as esb } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = await esb({ entryPoints: [path.join(here, 'gen.ts')], bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'warning' })
const mod = await import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'))
const p = mod.build()
const body = Object.entries(p)
  .filter(([k]) => k !== 'meta')
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  .join('\n')
const src = `// GENERATED by posters/run.mjs from gen.ts — do not edit. Sources and parameters are listed in gen.ts.
// ${JSON.stringify(p.meta)}
export const VB = { w: ${mod.W}, h: ${mod.H} }
export const posters = {
${body}
} as const
`
writeFileSync(path.join(here, 'data.ts'), src)
console.log('wrote data.ts', (src.length / 1024).toFixed(1) + ' KB', JSON.stringify(p.meta))
for (const [k, v] of Object.entries(p)) if (typeof v === 'string') console.log(k, (v.length / 1024).toFixed(1) + ' KB')
